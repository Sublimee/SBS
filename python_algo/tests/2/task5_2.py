# 5.3. Удаление узла

# Рефлексия

# В целом повторяем идею из 1. Сначала приводим дерево за исключением key к отсортированному массиву. По полученному
# отсортированному массиву строим дерево. Однако не смог понять фразу из постановки задачи: "Несмотря на отсутствие
# пустых мест, метод должен корректно перестраивать дерево, сохраняя балансировку.". Отсутствие пустых мест в пришедшем
# дереве не противоречит постановке задачи. В итоговом дереве тоже могут быть пустые места.

# O(N log N) / O(N)
def DeleteFromBBSTArray(tree: list[int | None], key: int) -> list[int | None]:
    if key not in tree:
        return tree

    sortedValues: list[int] = []
    for value in tree:
        if value is not None:
            sortedValues.append(value)

    sortedValues.remove(key)
    sortedValues.sort()

    result: list[int | None] = [None] * len(tree)
    BuildArrayRecursive(sortedValues, result, 0, len(sortedValues), 0)
    return result



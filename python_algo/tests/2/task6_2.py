# 6.2. Проверка правильности дерева

# Рефлексия

# Рекурсивно обходим дерево и для каждого узла проверяем:
# 1) ключ левого потомка должен быть меньше ключа родителя
# 2) ключ правого потомка должен быть больше или равен ключу родителя
#
# При отсутствии одного из потомков считаем условие выполненным. Если одно из условий нарушено, то возвращаем False.
# Деревья без корня или только с корнем считаем правильными.


class BalancedBSTWithCorrectnessCheck(BalancedBST):

    # O(N) / O(N)
    def IsCorrect(self) -> bool:
        return self.IsCorrectRecursive(self.Root)

    def IsCorrectRecursive(self, node: BSTNode | None) -> bool:
        if node is None:
            return True

        if node.LeftChild is not None and node.LeftChild.NodeKey >= node.NodeKey:
            return False

        if node.RightChild is not None and node.RightChild.NodeKey < node.NodeKey:
            return False

        return (
                self.IsCorrectRecursive(node.LeftChild)
                and self.IsCorrectRecursive(node.RightChild)
        )



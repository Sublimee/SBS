# 7.4. Поиск максимального элемента в диапазоне

# Рефлексия

# В идеале, конечно, снабжать класс информацией, является ли куча max или min. Но, как и в предыдущих заданиях
# ориентируемся только на свойство max.
#
# Так как ключи в куче "отсортированы" по убыванию (каждый путь от корня к листьям), то спускаясь от корня по
# поддеревьям, ищем первое вхождение ключа очередного узла в диапазон. Если значение было найдено, то возвращаем его
# вверх по стеку для сравнения с результатами поиска в других поддеревьях. Кроме того если:
# * корень меньше минимального значения из диапазона, то поиск не продолжаем
# * ключ узла меньше нижней границы диапазона, то ветку далее не обрабатываем


class HeapWithFindMaxInRange(Heap):

    # O(N) / O(log N)
    def FindMaxInRange(self, minValue: int, maxValue: int) -> int:
        if self.Size == 0:
            return -1

        return self.FindMaxInRangeRecursive(0, minValue, maxValue)

    def FindMaxInRangeRecursive(self, index: int, minValue: int, maxValue: int) -> int:
        if index >= self.Size:
            return -1

        key = self.HeapArray[index]
        if key < minValue:
            return -1

        if key <= maxValue:
            return key

        leftMax = self.FindMaxInRangeRecursive(2 * index + 1, minValue, maxValue)
        rightMax = self.FindMaxInRangeRecursive(2 * index + 2, minValue, maxValue)
        return max(leftMax, rightMax)


# 7.5. Поиск элемента меньше заданного значения

# Рефлексия

# В 7.4 мы уже использовали свойства кучи для эффективного поиска. Если нужно найти ключ меньше заданного значения, то
# нам нужно проверять листья, так как среди них есть минимальное значение во всём дереве. Берём из них первый попавшийся
# лист, удовлетворяющий условию. Если требовалось придумать универсальный алгоритм, то всё зависит от вариативности
# условий. Если условие предполагает использование упорядоченности дерева, то можем оптимизировать алгоритм за счёт
# анализа листьев и корня, иначе может потребоваться полный перебор.

class HeapWithFindLessThan(Heap):

    # O(N) / O(1)
    def FindLessThan(self, value: int) -> int:
        if self.Size == 0:
            return -1

        for index in range(self.Size // 2, self.Size):
            if self.HeapArray[index] < value:
                return self.HeapArray[index]

        return -1


# 7.6. Объединение куч

# Рефлексия

# Мержим поэлементно кучу-аргумент с текущей за счёт существующих методов Add и GetMax. Чтобы не вывалиться за границы
# массива, предварительно по необходимости расширяем его с помощью OfferSpace. Тот самый "один дополнительный метод в
# интерфейс". Этот метод можно было бы внедрить в существующий Add, но у метода неподходящий для этого контракт. Если
# обращение к размеру тоже недопустимо, то перед каждым Add можно делать сравнение Size и len(self.HeapArray) для оценки
# необходимости увеличения размера массива на число листьев нового уровня.
#
# GetMax модифицирует переданную кучу, что не всегда может быть приемлемо. С учётом ограничения на методы интерфейса это
# решение единственное в условиях имеющихся ограничений. Можно было бы её восстановить обратно вызовами методов Add, но
# это уже перебор).
#
# Add и GetMax не нарушают контракт кучи, в тестах проверяю IsHeap для проверки реализации.

class HeapWithMerge(Heap):

    # O(N log N) / O(N)
    def Merge(self, other: Heap) -> None:
        if other is self:
            return

        self.OfferSpace(self.Size + other.Size)

        key = other.GetMax()
        while key != -1:
            self.Add(key)
            key = other.GetMax()


    def OfferSpace(self, requiredSize: int) -> None:
        capacity = len(self.HeapArray)
        if capacity >= requiredSize:
            return

        while capacity < requiredSize:
            capacity = 2 * capacity + 1

        self.HeapArray.extend([None] * (capacity - len(self.HeapArray)))


